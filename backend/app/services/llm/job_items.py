import os

from langchain_core.prompts import ChatPromptTemplate
from langchain_ollama import ChatOllama

from .general import GeneralLLMClient

'''
- Если язык вакансии {lang} — русский или не указан, начни ровно с этих двух строк:
Добрый день!

Я заинтересован в вакансии {name}.
- Название вакансии {name} ставь в правильном падеже: "заинтересован в вакансии <название>".
- Если язык вакансии {lang} не русский — напиши короткое приветствие и фразу заинтересованности в вакансии {name} на языке {lang}.
- После приветствия с новой строки переходи к описанию проектов.
'''
_MODEL="qwen2.5:7b"
# _MODEL="qwen3.5:latest"
# _MODEL="mistral:7b"
class CoverLetterPrompt(GeneralLLMClient):

    def __init__(self):
        base_url = os.getenv("OLLAMA_HOST", "http://localhost:11434")
        model = ChatOllama(model=_MODEL, temperature=0, base_url=base_url,top_k=5)
        super().__init__(model=model)

    def get_schema(self):
        return None
    
    @property
    def prompt_template(self):
        system_message = """
        Ты — карьерный консультант. Пишешь сопроводительные письма для IT-специалистов.
 
ФОРМАТ ВЫВОДА:
- Только plain text
- Никаких **, ---, #, маркеров списков
- Никаких обращений типа "Дорогой HR" или "Dear Hiring Manager"
- Язык: значение поля lang. Если lang пусто — русский.
- Длина: 180–280 слов. Считай слова. Не выходи за границы.
- Лицо: от первого лица
 
СТРУКТУРА ПИСЬМА (строго в этом порядке):
 
1. ПРИВЕТСТВИЕ
Напиши дословно:
"Добрый день меня заинтересовала ваша вакансия. Думаю мой релевантный опыт подойдет под ваши требования и нужды."
Перед этой строкой — ничего.
 
2. ТЕХНОЛОГИИ
Выбери 3–5 технологий из vacancy_technologies, которые есть в user_projects.
Только пересечение. Упомяни их в одном-двух предложениях связного текста, не списком.
 
3. ПРОЕКТЫ
Напиши заголовок: "Мои достижения и проекты:"
 
ШАГ 0 — ФИЛЬТР РОЛИ (выполни до выбора проектов):
Определи тип роли из поля name: frontend / backend / fullstack / devops / mobile / data / другое.
Затем для каждого проекта из user_projects определи его тип по тем же категориям.
Берём только проекты, чей тип совпадает с типом вакансии.
 
Если тип не совпадает — проект НЕЛЬЗЯ брать как основной, даже если в нём есть нужные технологии.
Исключение: fullstack-вакансия принимает и frontend, и backend проекты.
 
Примеры фильтрации (не копировать, только логика):
- Вакансия "Frontend разработчик" — проект с REST API, Node.js, базами данных → не подходит как основной
- Вакансия "Backend разработчик" — проект с React, CSS, версткой → не подходит как основной
- Вакансия "Frontend разработчик" — проект с Vue, React, TypeScript → подходит
 
Проект 1 (только совпадающий по роли):
- Начни с названия проекта
- Выбери из отфильтрованных проектов тот, что лучше всего совпадает с vacancy_requirements
- Опиши в 3–4 предложениях
- Каждое предложение: [что сделал] + [какой инструмент/технологию использовал] + [число или измеримый результат]
- Если цифр нет в данных — придумай реалистичные (RPS, мс, % прирост)
- После описания: "Стек: [технологии только из vacancy_technologies]"
 
Проект 2 :
- Начни с названия проекта
- Тоже должен совпадать по роли, либо иметь пересечение > 50% с vacancy_requirements
- 1–2 предложения по той же схеме
- Не повторяй технологии из Проекта 1 и блока Технологии
- Если подходящего второго проекта нет — не пиши Проект 2 совсем
 
ЗАПРЕТ в блоке проектов:
- Нельзя брать backend-проект для frontend-вакансии и наоборот
- Нельзя писать: "улучшил UX", "повысил эффективность", "оптимизировал" без цифры
- Нельзя: "командный игрок", "быстро обучаюсь", "стрессоустойчив"
- Нельзя упоминать технологии не из vacancy_technologies и не из vacancy_requirements
- Нельзя называть project_name своим проектом
 
4. ПОДПИСЬ
Если user_first_name и user_last_name заполнены — напиши: "С уважением, [Имя] [Фамилия]"
Если оба пусты — напиши нейтральную фразу о готовности к интервью.
        """
        human_message = """

        ИМЯ И ФАМИЛИЯ КАНДИДАТА: {user_first_name} {user_last_name}
        
        ЯЗЫК ВАКАНСИИ:
        {lang}
        
        НАЗВАНИЕ ВАКАНСИИ:
        {name}

        НАЗВАНИЕ ПРОЕКТА/КОМПАНИИ РАБОТОДАТЕЛЯ:
        {project_name}

        ТРЕБОВАНИЯ ВАКАНСИИ И КЛЮЧЕВЫЕ СЛОВА:
        {vacancy_requirements}
        ТЕХНОЛОГИИ ВАКАНСИИ 
        {vacancy_technologies}

        МОИ ПРОЕКТЫ (JSON):
        {user_projects}
        Напиши письмо сейчас."""
        
        return ChatPromptTemplate.from_messages([system_message,human_message])